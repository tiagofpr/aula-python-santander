# Variáveis são usadas para armazenar valores que podem ser usados posteriormente no código. 
# Em Python, não é necessário declarar o tipo da variável, pois ele é inferido automaticamente com base no valor atribuído.

#Também é possível atribuir múltiplos valores a múltiplas variáveis em uma única linha:
x, y, z = 10, 20, 30
a = b = c = 10 # nesse caso , todas as variáveis a, b e c recebem o mesmo valor 10.

